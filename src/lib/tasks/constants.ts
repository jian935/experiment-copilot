/**
 * 巡检的常量。
 *
 * 纪律与 `config.ts` 一致：**这些值只能在这里定义**，散落到别处就等于没有口径。
 * 但这里只放「巡检自己的参数」——决策阈值（α、SRM、护栏 margin）一律读 `DEFAULT_CONFIG`，
 * 巡检不复制它们，否则设置页一改就会出现两套 α。
 */

/** 「业务关心的最小效应」：相对对照基线的 3%。这是业务声明，不是统计默认值 */
export const MATERIALITY_REL = 0.03;

/**
 * 「要补样本」与「设计不足」的分界：MDE / 业务效应量。
 *
 * 为什么需要这条线：如果 MDE 是业务效应的 4 倍，补样本要 16 倍的人数——
 * 那不是建议，那是劝人放弃。所以超过 2.5 倍时给出的结论改成
 * 「这个实验按现在的规模回答不了这个问题」，而不再假装有补救办法。
 */
export const N_RATIO_LIMIT = 2.5;

/**
 * 几个实验同时出现同一类「基础设施」信号，才判为系统性问题。
 *
 * 只对 SRM / 无数据 / 数据停滞这三类判——它们共用分流、埋点、导出同一条链路。
 * 护栏恶化和主指标负向**永远不判系统性**：那是不同功能的业务结论，
 * 15 个功能各有一个坏结论是正常的，不是某个共因造成的。
 */
export const INFRA_SYSTEMIC_MIN = 3;

/** 超过几天没有新增数据算「停滞」 */
export const STALE_DEFAULT = 3;

/**
 * critical 的上限。
 *
 * 为什么需要上限：如果一次巡检有 12 个实验「必须今天看」，那实际信息不是 12 件事，
 * 而是「有 1 件共用的坏事」。逐条列 12 个反而会让人逐个去查，
 * 而真正的修法通常在分流服务或埋点发布这一层。所以超限时改成报系统性问题。
 */
export const CRITICAL_LIMIT = 5;

/** 巡检估算「还要几天」时用的功效口径（与 `forecast.ts` 的默认一致） */
export const POWER_DEFAULT = 0.8;

/** 报告开头必须写清的边界。不写这些，读者会把巡检当成「一切正常」的证明 */
export const INSPECTION_SCOPE = [
  '回答的是「哪个实验需要人现在介入、介入做什么」，不是「所有实验都正常」',
  '排序依据是「不处理的代价」，不是效应大小：分流坏了的实验排第一，是因为那组数字不能用',
  '「测不出」与「确实没效果」是两个结论，分界是业务声明的效应量（默认相对 3%）',
  '基准日是数据里最晚的一天，不是系统时钟——所以同一份数据永远得到同一份周报',
  '不含任何模型生成的数字：所有数字来自引擎，每条结论都带证据编号',
] as const;
